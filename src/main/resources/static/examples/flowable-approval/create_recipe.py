"""Compile public Flowable reference shapes to ordinary faker-data rules.

The reference contains fixed model/runtime shape, not generated rows. All new IDs,
ordinary values and references are generated by the faker-data engine. Only the
Java-serialized BYTES_ field uses a field-only extension.
"""
import json
from pathlib import Path
import sys

def rule(code, **kw): return {'code':code, **kw}
def literal(value):
    if value is None: return []
    return [rule('RES.INPUTAREA', inputs=[{'value':str(value), 'weight':1}])]
def col(name, java='java.lang.String', regs=None, virtual=False):
    return {'name':name, 'javaType':java,'nullable':1,'virtual':virtual,'regs':regs or []}
def ref(table,name): return [rule('REF.OTHER_TABLE',refOtherTableColumn=[table,name])]
def create_recipe(templates, state, count):
    if state not in {'SAVED','SUBMITTED','APPROVED'} or type(count) is not int or not 1<=count<=1000:
        raise ValueError('Use SAVED/SUBMITTED/APPROVED and 1..1000 documents')
    sample=templates.get(state, {'tables':{}})
    tokens=sorted(sample.get('idTokens', {str(row['ID_']) for t in sample['tables'].values() for row in t['rows']}))
    if len(tokens)>45: raise ValueError('Reference shape exceeds virtual token budget')
    aliases={token:'flow_key_'+str(i) for i,token in enumerate(tokens)}
    root={'name':'FD_DOCUMENTS','size':count,'columns':[
        col('ID',regs=[rule('FIX.UUID')]),col('STATE',regs=literal(state)),
        col('OWNER',regs=literal('owner')),col('REVIEWER',regs=literal('reviewer')),col('AUDITOR',regs=literal('auditor')),
        col('SUBJECT',regs=literal('Public document ')+[rule('REF.SELF_COLUMN',refSelfColumn='ID')]),
        col('AMOUNT','java.math.BigDecimal',literal(200)),
        col('PROCESS_ID',regs=[] if state=='SAVED' else [rule('REF.SELF_COLUMN',refSelfColumn=aliases[str(sample['processId'])])])]
    }
    root['columns'] += [col(alias,regs=[rule('FIX.UUID')],virtual=True) for alias in aliases.values()]
    tables=[root,{'name':'FD_LINES','size':0,'parentRows':{'table':'FD_DOCUMENTS','rowsPerParent':2},'columns':[
        col('ID',regs=[rule('FIX.UUID')]),col('DOC_ID',regs=ref('FD_DOCUMENTS','ID')),
        col('AMOUNT','java.math.BigDecimal',literal(100))]}]
    for table,shape in sample['tables'].items():
        rows=shape['rows']
        if table=='ACT_RU_EXECUTION':
            rows=sorted(rows,key=lambda row:row.get('PARENT_ID_') is not None)
        n=len(rows)
        def cell(name,value):
            if name=='BUSINESS_KEY_' and value=='template-document': return ref('FD_DOCUMENTS','ID')
            if isinstance(value,str) and value in aliases: return ref('FD_DOCUMENTS',aliases[value])
            return literal(value)
        columns=[]
        for metadata in shape['columns']:
            name=metadata['name']; java=metadata['javaType']
            if java=='[B':
                if name!='BYTES_' or table!='ACT_GE_BYTEARRAY': raise ValueError('Unsupported binary reference field')
                regs=[rule('EXT.FIELD',extension='flowable-public-payload')] if any(r[name] is not None for r in rows) else []
            else:
                values=[r[name] for r in rows]
                regs=cell(name,values[-1])
                for index in reversed(range(n-1)):
                    if values[index]!=values[-1] or isinstance(values[index],str) and values[index] in aliases:
                        regs=[rule('COND.EXPR',condition=f'#__rowIndex % {n} == {index}',onTrue=cell(name,values[index]),onFalse=regs)]
            columns.append(col(name,java,regs))
        columns.append(col('fixture_document',regs=ref('FD_DOCUMENTS','ID'),virtual=True))
        # Rule dependencies must also preserve physical FK insert order. These
        # virtual columns never enter the target schema and generate no new IDs.
        deps=sorted({fk['table'] for fk in shape.get('foreignKeys',[]) if fk['table'] in sample['tables'] and fk['table']!=table})
        for index,dep in enumerate(deps): columns.append(col('fixture_dependency_'+str(index),regs=ref(dep,'ID_'),virtual=True))
        tables.append({'name':table,'size':0,'parentRows':{'table':'FD_DOCUMENTS','rowsPerParent':n},'columns':columns})
    return {'tables':tables}

if __name__=='__main__':
    print(json.dumps(create_recipe(json.loads(Path(sys.argv[1]).read_text(encoding='utf-8-sig')),sys.argv[2],int(sys.argv[3])),indent=2))
